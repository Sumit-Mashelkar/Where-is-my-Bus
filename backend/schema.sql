CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(30) NOT NULL,
    email VARCHAR(40) UNIQUE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS buses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_number VARCHAR(50) UNIQUE,
    bus_name VARCHAR(50) NOT NULL UNIQUE,
    from_city VARCHAR(100) NOT NULL,
    to_city VARCHAR(100) NOT NULL,
    departure TIME NOT NULL
    -- departure needs to be removed  =========================================  <--
);

CREATE TABLE IF NOT EXISTS route_stops (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_id INTEGER NOT NULL REFERENCES buses(id) ON DELETE CASCADE,
    stop_order INTEGER NOT NULL CHECK(stop_order > 0),
    stop_name VARCHAR(100) NOT NULL,
    arrival_time TEXT,
    UNIQUE (bus_id, stop_order)  
);

-- stores all the updates even unverified
CREATE TABLE IF NOT EXISTS bus_reports (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_id INTEGER NOT NULL REFERENCES buses(id) ON DELETE RESTRICT,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    current_stop_id INTEGER REFERENCES route_stops(id) ON DELETE SET NULL,
    direction VARCHAR(100),
    updates VARCHAR(100),
    vote INTEGER DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- stores only the verified reports
CREATE TABLE IF NOT EXISTS bus_reports_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_number VARCHAR(50),
    current_stop VARCHAR(100),
    direction VARCHAR(100),
    updates VARCHAR(100),
    vote INTEGER DEFAULT 0,
    verified_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

